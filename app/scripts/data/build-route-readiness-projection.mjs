#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import { buildDeepAudit } from './audit-deep.mjs';

const GENERATED_FILE = join('src', 'data', 'route-readiness.generated.ts');
const DISPLAYABLE_SOURCE_READINESS = new Set(['blocked', 'partial', 'source-backed']);

export function buildRouteReadinessProjection(appRoot = process.cwd(), options = {}) {
  const audit = options.audit ?? buildDeepAudit(appRoot, { generatedAt: 'projection-check' });
  const targetMetricValidation = audit.targetMetricContractValidation;
  if (targetMetricValidation?.passed !== true) {
    const validationErrors = Array.isArray(targetMetricValidation?.errors)
      ? targetMetricValidation.errors
        .map((error) => [error?.path, error?.code].filter(Boolean).join(':'))
        .filter(Boolean)
      : [];
    const detail = validationErrors.length > 0 ? `: ${validationErrors.join('; ')}` : '';
    throw new Error(`Target metric contract validation failed${detail}`);
  }

  const businessRoutes = audit.routeEvidenceMatrix.filter((row) => !row.embedded && row.route !== '*');
  const projectionErrors = businessRoutes.flatMap((row) => {
    const errors = [];
    if (!DISPLAYABLE_SOURCE_READINESS.has(row.source_readiness)) {
      errors.push(`${row.route}: source_readiness=${row.source_readiness}`);
    }
    if (row.target_metric_contract_status !== 'defined-not-certified') {
      errors.push(`${row.route}: target_metric_contract_status=${row.target_metric_contract_status}`);
    }
    if (!row.target_metric_contract_id || !row.target_metric_name || !row.target_metric_owner || !row.target_metric_grain) {
      errors.push(`${row.route}: target metric identity is incomplete`);
    }
    return errors;
  });

  if (projectionErrors.length > 0) {
    throw new Error(`Source readiness projection rejected: ${projectionErrors.join('; ')}`);
  }

  return {
    contractVersion: audit.targetMetricContracts.contractVersion,
    contractGeneratedAt: audit.targetMetricContracts.generatedAt,
    generatedRule:
      'Local projection of the deep-audit route evidence matrix. Source readiness describes fact-support scope only; it never certifies decision readiness.',
    routes: businessRoutes.map((row) => ({
      route: row.route,
      component: row.component,
      sourceReadiness: row.source_readiness,
      sourceCount: row.source_count,
      displayableSourceCount: row.displayable_source_count,
      blockedSourceCount: row.blocked_source_count,
      scopeGapSourceCount: row.scope_gap_source_count,
      targetMetricContractStatus: row.target_metric_contract_status,
      targetMetricId: row.target_metric_contract_id,
      targetMetricName: row.target_metric_name,
      targetMetricOwner: row.target_metric_owner,
      targetMetricGrain: row.target_metric_grain,
      decisionReady: row.decision_ready,
    })),
  };
}

export function serializeRouteReadinessProjection(projection) {
  return [
    '// This file is generated by scripts/data/build-route-readiness-projection.mjs.',
    '// Do not edit it by hand; run npm run data:route-readiness:build.',
    `export const routeReadinessProjection = ${JSON.stringify(projection, null, 2)} as const;`,
    '',
  ].join('\n');
}

function main() {
  const appRoot = process.cwd();
  const targetPath = join(appRoot, GENERATED_FILE);
  const expected = serializeRouteReadinessProjection(buildRouteReadinessProjection(appRoot));
  const checkOnly = process.argv.includes('--check');

  if (checkOnly) {
    const actual = readFileSync(targetPath, 'utf8');
    if (actual !== expected) {
      process.stderr.write(
        `Route readiness projection is stale: ${relative(appRoot, targetPath)}. Run npm run data:route-readiness:build.\n`,
      );
      process.exitCode = 1;
      return;
    }
    process.stdout.write(`Route readiness projection is current: ${relative(appRoot, targetPath)}\n`);
    return;
  }

  writeFileSync(targetPath, expected);
  process.stdout.write(`Wrote ${relative(appRoot, targetPath)}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
